"""Render bench/results/*.json into docs/benchmarks.md plus charts.

Usage: python bench/report.py [--results bench/results --out docs/benchmarks.md]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402


def load(results: Path) -> list[dict[str, object]]:
    rows = []
    for path in sorted(results.glob("*.json")):
        rows.append(json.loads(path.read_text(encoding="utf-8")))
    return rows


def by_label(rows: list[dict[str, object]]) -> dict[str, dict[str, object]]:
    return {str(r["label"]): r for r in rows}


def _f(row: dict[str, object], key: str) -> float:
    value = row[key]
    assert isinstance(value, (int, float))
    return float(value)


def _s(row: dict[str, object], key: str) -> str:
    return str(row[key])


def table(headers: list[str], rows: list[list[object]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        out.append("| " + " | ".join(str(c) for c in row) + " |")
    return "\n".join(out) + "\n"


def bar(path: Path, title: str, labels: list[str], values: list[float], ylabel: str) -> None:
    fig, ax = plt.subplots(figsize=(8, 4))
    bars = ax.bar(labels, values)
    ax.set_title(title)
    ax.set_ylabel(ylabel)
    for bar_, value in zip(bars, values, strict=True):
        ax.text(
            bar_.get_x() + bar_.get_width() / 2,
            bar_.get_height(),
            f"{value:,.0f}",
            ha="center",
            va="bottom",
            fontsize=9,
        )
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def grouped(
    path: Path, title: str, groups: list[str], series: dict[str, list[float]], ylabel: str
) -> None:
    import numpy as np

    x = np.arange(len(groups))
    width = 0.8 / max(1, len(series))
    fig, ax = plt.subplots(figsize=(9, 4))
    for i, (name, values) in enumerate(series.items()):
        ax.bar(x + i * width, values, width, label=name)
    ax.set_xticks(x + width * (len(series) - 1) / 2)
    ax.set_xticklabels(groups)
    ax.set_title(title)
    ax.set_ylabel(ylabel)
    ax.legend()
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description="Render benchmark report")
    parser.add_argument("--results", default="bench/results")
    parser.add_argument("--out", default="docs/benchmarks.md")
    parser.add_argument("--imgdir", default="docs")
    args = parser.parse_args()
    results_dir = Path(args.results)
    out_path = Path(args.out)
    imgdir = Path(args.imgdir)
    imgdir.mkdir(parents=True, exist_ok=True)

    rows = load(results_dir)
    by = by_label(rows)
    machine = rows[0]["machine"] if rows else {}
    assert isinstance(machine, dict)

    def get(label: str) -> dict[str, object]:
        if label not in by:
            raise SystemExit(f"missing result for {label}; run bench/run_bench.py first")
        return by[label]

    lines = []
    lines.append("# Benchmarks\n")
    lines.append(
        "> Generated by `bench/report.py` from real runs. "
        "Reproduce with the commands in each section.\n"
    )
    lines.append("## Machine\n")
    lines.append(f"- platform: `{machine.get('platform', '?')}`")
    lines.append(f"- python: `{machine.get('python', '?')}`")
    lines.append(f"- cpus: `{machine.get('cpus', '?')}`")
    lines.append(
        "- storage: local APFS (macOS `fsync` without FULLSYNC is cheap; "
        "on Linux/ext4 expect a wider always-vs-batch gap)"
    )
    lines.append("")

    # Comparison 1: fsync policies.
    fsync_labels = ["lsm-write-always", "lsm-write-batch", "lsm-write-never"]
    fsync_rows = [get(label) for label in fsync_labels]
    lines.append("## 1. Single-node LSM: fsync policy (write-only, 128B, 8s)\n")
    lines.append("`python bench/run_bench.py --suite lsm-fsync`\n")
    lines.append(
        table(
            ["fsync", "ops/s", "p50 ms", "p95 ms", "p99 ms"],
            [
                [r["fsync"], r["ops_per_sec"], r["p50_ms"], r["p95_ms"], r["p99_ms"]]
                for r in fsync_rows
            ],
        )
    )
    bar(
        imgdir / "bench-fsync.png",
        "LSM writes/s by fsync policy",
        [str(r["fsync"]) for r in fsync_rows],
        [_f(r, "ops_per_sec") for r in fsync_rows],
        "ops/s",
    )
    lines.append("![fsync](bench-fsync.png)\n")

    # Comparison 2: group commit on/off.
    batch_labels = ["cluster-write-batch-on", "cluster-write-batch-off"]
    batch_rows = [get(label) for label in batch_labels]
    lines.append("## 2. 3-node cluster: group commit (write-only 128B, 16 clients, 10s)\n")
    lines.append("`python bench/run_bench.py --suite cluster-batch`\n")
    lines.append(
        table(
            ["batching", "ops/s", "p50 ms", "p95 ms", "p99 ms"],
            [
                [r["batching"], r["ops_per_sec"], r["p50_ms"], r["p95_ms"], r["p99_ms"]]
                for r in batch_rows
            ],
        )
    )
    bar(
        imgdir / "bench-batch.png",
        "Cluster writes/s: group commit on vs off",
        ["on" if r["batching"] else "off" for r in batch_rows],
        [_f(r, "ops_per_sec") for r in batch_rows],
        "ops/s",
    )
    lines.append("![batch](bench-batch.png)\n")

    # Comparison 3: read modes.
    read_labels = ["cluster-read-linearizable", "cluster-read-stale"]
    read_rows = [get(label) for label in read_labels]
    lines.append("## 3. Reads: ReadIndex vs stale (read-only 128B, 16 clients, 10s)\n")
    lines.append("`python bench/run_bench.py --suite reads`\n")
    lines.append(
        table(
            ["mode", "ops/s", "p50 ms", "p95 ms", "p99 ms"],
            [
                [r["read_mode"], r["ops_per_sec"], r["p50_ms"], r["p95_ms"], r["p99_ms"]]
                for r in read_rows
            ],
        )
    )
    bar(
        imgdir / "bench-reads.png",
        "Reads/s: linearizable vs stale",
        [str(r["read_mode"]) for r in read_rows],
        [_f(r, "ops_per_sec") for r in read_rows],
        "ops/s",
    )
    lines.append("![reads](bench-reads.png)\n")

    # Comparison 4: bloom on/off.
    bloom_labels = ["lsm-miss-bloom-on", "lsm-miss-bloom-off"]
    bloom_rows = [get(label) for label in bloom_labels]
    lines.append("## 4. Bloom filter: missing-key reads (20k keys on SSTables, 8s)\n")
    lines.append("`python bench/run_bench.py --suite bloom`\n")
    lines.append(
        table(
            ["bloom", "ops/s", "p50 ms", "p95 ms", "p99 ms"],
            [
                [r["bloom"], r["ops_per_sec"], r["p50_ms"], r["p95_ms"], r["p99_ms"]]
                for r in bloom_rows
            ],
        )
    )
    bar(
        imgdir / "bench-bloom.png",
        "Missing-key reads/s: bloom on vs off",
        ["on" if r["bloom"] else "off" for r in bloom_rows],
        [_f(r, "ops_per_sec") for r in bloom_rows],
        "ops/s",
    )
    lines.append("![bloom](bench-bloom.png)\n")

    # Headline matrix.
    lines.append("## Headline: 3-node cluster, workloads x concurrency (128B, 8s)\n")
    lines.append("`python bench/run_bench.py --suite headline`\n")
    head_labels = [
        "cluster-write_only-128B-c1",
        "cluster-write_only-128B-c16",
        "cluster-write_only-128B-c64",
        "cluster-mixed-128B-c1",
        "cluster-mixed-128B-c16",
        "cluster-mixed-128B-c64",
        "cluster-read_only-128B-c1",
        "cluster-read_only-128B-c16",
        "cluster-read_only-128B-c64",
        "cluster-write-4KiB-c16",
    ]
    head_rows = [get(label) for label in head_labels]
    lines.append(
        table(
            ["workload", "conc", "ops/s", "p50 ms", "p95 ms", "p99 ms"],
            [
                [
                    r["workload"],
                    r["concurrency"],
                    r["ops_per_sec"],
                    r["p50_ms"],
                    r["p95_ms"],
                    r["p99_ms"],
                ]
                for r in head_rows
            ],
        )
    )
    grouped(
        imgdir / "bench-headline.png",
        "Cluster throughput by workload and concurrency",
        ["c1", "c16", "c64"],
        {
            "write-only": [_f(head_rows[i], "ops_per_sec") for i in (0, 1, 2)],
            "mixed": [_f(head_rows[i], "ops_per_sec") for i in (3, 4, 5)],
            "read-only": [_f(head_rows[i], "ops_per_sec") for i in (6, 7, 8)],
        },
        "ops/s",
    )
    lines.append("![headline](bench-headline.png)\n")
    four_k = head_rows[9]
    lines.append(
        f"4 KiB values (write-only, 16 clients): **{four_k['ops_per_sec']} ops/s** "
        f"(p50 {four_k['p50_ms']}ms, p99 {four_k['p99_ms']}ms) -- payload-dominated, "
        "as expected.\n"
    )
    lines.append("## Notes and limits\n")
    lines.append(
        "- localhost, single machine: no real network; multi-machine numbers would be lower.\n"
        "- fsync=always on this box is cheap (APFS); treat the LSM gap as a lower bound.\n"
        "- The store saturates around ~1.3k writes/s here (raft log + LSM WAL + "
        "progress meta fsyncs per write); batching on/off moves it ~35%.\n"
        "- Linearizable reads cost a heartbeat round (~10x stale at 16 clients).\n"
        "- Bloom filters pay ~4x on missing-key reads over on-disk tables.\n"
    )
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
